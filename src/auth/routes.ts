import { eq } from 'drizzle-orm';
import { Hono, type Context } from 'hono';
import { z } from 'zod';

import type { Db } from '../db/client';
import { PLATFORMS, users } from '../db/schema';
import type { AppEnv, Config } from '../env';
import { AppError } from '../lib/app-error';
import { parseBody } from '../lib/validation';
import { authRateLimit, requireAuth } from './middleware';
import {
  type ClientMeta,
  createSession,
  revokeSession,
  rotateSession,
} from './sessions';
import { sameSecret } from './tokens';

export const userResponseColumns = {
  id: users.id,
  email: users.email,
  fullName: users.fullName,
  role: users.role,
  isActive: users.isActive,
  createdAt: users.createdAt,
};

/** Optional device info sent by the mobile app; one session is kept per device. */
const deviceFields = {
  /** Stable per-install id generated by the app. */
  deviceId: z.string().max(200).optional(),
  /** Human readable, e.g. "Pixel 8". */
  deviceName: z.string().max(200).optional(),
  platform: z.enum(PLATFORMS).optional(),
};

const loginSchema = z.strictObject({
  email: z.string().trim().toLowerCase().pipe(z.email().max(254)),
  password: z.string().min(1).max(128),
  ...deviceFields,
});

const refreshSchema = z.strictObject({
  refreshToken: z.string().min(1).max(512),
});

const invalidCredentials = () =>
  AppError.unauthorized(
    'INVALID_CREDENTIALS',
    'Email or password is incorrect',
  );

function clientMeta(c: Context): ClientMeta {
  return {
    ip: c.req.header('cf-connecting-ip') ?? undefined,
    userAgent: c.req.header('user-agent')?.slice(0, 500),
  };
}

/** The configured account's row, created on first sign-in. It is always an ADMIN. */
async function upsertAdmin(db: Db, config: Config) {
  const [user] = await db
    .insert(users)
    .values({
      email: config.ADMIN_EMAIL,
      fullName: config.ADMIN_NAME,
      role: 'ADMIN',
      passwordHash: '!',
    })
    .onConflictDoUpdate({ target: users.email, set: { role: 'ADMIN' } })
    .returning(userResponseColumns);
  return user;
}

/**
 * Single-account mode: the only credentials accepted are ADMIN_EMAIL / ADMIN_PASSWORD from the Worker's
 * secrets (no registration, no password hashing). Sessions and token rotation work as before.
 */
export const authRoutes = new Hono<AppEnv>()
  .post('/login', authRateLimit, async (c) => {
    const input = await parseBody(c, loginSchema);
    const config = c.var.config;
    // Compare both values every time so timing does not reveal which one was wrong.
    const emailOk = sameSecret(input.email, config.ADMIN_EMAIL);
    const passwordOk = sameSecret(input.password, config.ADMIN_PASSWORD);
    if (!emailOk || !passwordOk) throw invalidCredentials();

    const db = c.var.db;
    const user = await upsertAdmin(db, config);
    if (!user.isActive) {
      throw new AppError(
        403,
        'ACCOUNT_DISABLED',
        'This account has been disabled',
      );
    }
    const tokens = await createSession(
      db,
      config,
      user.id,
      input,
      clientMeta(c),
    );
    return c.json({ user, ...tokens }, 200);
  })

  /** Exchanges a refresh token for a new access + refresh token pair (the old refresh token is rotated). */
  .post('/refresh', authRateLimit, async (c) => {
    const { refreshToken } = await parseBody(c, refreshSchema);
    const db = c.var.db;
    const { userId, tokens } = await rotateSession(
      db,
      c.var.config,
      refreshToken,
      clientMeta(c),
    );
    const [user] = await db
      .select(userResponseColumns)
      .from(users)
      .where(eq(users.id, userId));
    return c.json({ user, ...tokens }, 200);
  })

  /** Ends the current device session; its access token stops working immediately. */
  .post('/logout', requireAuth, async (c) => {
    await revokeSession(c.var.db, c.var.user.sessionId);
    return c.body(null, 204);
  })

  .get('/me', requireAuth, async (c) => {
    const db = c.var.db;
    const [user] = await db
      .select(userResponseColumns)
      .from(users)
      .where(eq(users.id, c.var.user.id));
    return c.json(user);
  });
