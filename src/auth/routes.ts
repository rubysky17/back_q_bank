import { eq } from 'drizzle-orm';
import { Hono, type Context } from 'hono';
import { z } from 'zod';

import { isUniqueViolation } from '../db/errors';
import { PLATFORMS, users } from '../db/schema';
import type { AppEnv } from '../env';
import { AppError } from '../lib/app-error';
import { parseBody } from '../lib/validation';
import { authRateLimit, requireAuth } from './middleware';
import {
  hashPassword,
  needsRehash,
  simulatePasswordCheck,
  verifyPassword,
} from './password';
import {
  type ClientMeta,
  createSession,
  revokeSession,
  rotateSession,
} from './sessions';

export const userResponseColumns = {
  id: users.id,
  email: users.email,
  fullName: users.fullName,
  role: users.role,
  isActive: users.isActive,
  createdAt: users.createdAt,
};

/** Optional device info sent by the mobile app; one session is kept per device. */
const deviceFields = {
  /** Stable per-install id generated by the app. */
  deviceId: z.string().max(200).optional(),
  /** Human readable, e.g. "Pixel 8". */
  deviceName: z.string().max(200).optional(),
  platform: z.enum(PLATFORMS).optional(),
};

const email = z.string().trim().toLowerCase().pipe(z.email().max(254));

const loginSchema = z.strictObject({
  email,
  password: z.string().min(1).max(128),
  ...deviceFields,
});

export const PASSWORD_MIN_LENGTH = 8;

/** Self-service sign-up. The role is always USER; hosts and admins are promoted in the database. */
const registerSchema = z.strictObject({
  email,
  password: z.string().min(PASSWORD_MIN_LENGTH).max(128),
  fullName: z.string().trim().min(1).max(100),
  ...deviceFields,
});

const refreshSchema = z.strictObject({
  refreshToken: z.string().min(1).max(512),
});

const invalidCredentials = () =>
  AppError.unauthorized(
    'INVALID_CREDENTIALS',
    'Email or password is incorrect',
  );

function clientMeta(c: Context): ClientMeta {
  return {
    ip: c.req.header('cf-connecting-ip') ?? undefined,
    userAgent: c.req.header('user-agent')?.slice(0, 500),
  };
}

/**
 * Email + password accounts stored in the User table (passwords hashed with PBKDF2, see password.ts).
 * Anyone can register as USER; admins are created by the seed script.
 */
export const authRoutes = new Hono<AppEnv>()
  .post('/register', authRateLimit, async (c) => {
    const input = await parseBody(c, registerSchema);
    const config = c.var.config;
    const db = c.var.db;
    const passwordHash = await hashPassword(
      input.password,
      config.PASSWORD_HASH_ITERATIONS,
    );
    let user;
    try {
      [user] = await db
        .insert(users)
        .values({
          email: input.email,
          fullName: input.fullName,
          passwordHash,
          role: 'USER',
        })
        .returning(userResponseColumns);
    } catch (error) {
      if (isUniqueViolation(error, 'User.email')) {
        throw AppError.conflict(
          'EMAIL_TAKEN',
          'An account with this email already exists',
        );
      }
      throw error;
    }
    const tokens = await createSession(
      db,
      config,
      user.id,
      input,
      clientMeta(c),
    );
    return c.json({ user, ...tokens }, 201);
  })

  .post('/login', authRateLimit, async (c) => {
    const input = await parseBody(c, loginSchema);
    const config = c.var.config;
    const db = c.var.db;
    const [account] = await db
      .select({ ...userResponseColumns, passwordHash: users.passwordHash })
      .from(users)
      .where(eq(users.email, input.email))
      .limit(1);
    if (!account) {
      // Same work as a real check so timing does not reveal which emails exist.
      await simulatePasswordCheck(
        input.password,
        config.PASSWORD_HASH_ITERATIONS,
      );
      throw invalidCredentials();
    }
    const { passwordHash, ...user } = account;
    if (!(await verifyPassword(input.password, passwordHash))) {
      throw invalidCredentials();
    }
    if (!user.isActive) {
      throw new AppError(
        403,
        'ACCOUNT_DISABLED',
        'This account has been disabled',
      );
    }

    const iterations = config.PASSWORD_HASH_ITERATIONS;
    const rehash = needsRehash(passwordHash, iterations)
      ? db
          .update(users)
          .set({ passwordHash: await hashPassword(input.password, iterations) })
          .where(eq(users.id, user.id))
      : undefined;
    const [tokens] = await Promise.all([
      createSession(db, config, user.id, input, clientMeta(c)),
      rehash,
    ]);
    return c.json({ user, ...tokens }, 200);
  })

  /** Exchanges a refresh token for a new access + refresh token pair (the old refresh token is rotated). */
  .post('/refresh', authRateLimit, async (c) => {
    const { refreshToken } = await parseBody(c, refreshSchema);
    const db = c.var.db;
    const { userId, tokens } = await rotateSession(
      db,
      c.var.config,
      refreshToken,
      clientMeta(c),
    );
    const [user] = await db
      .select(userResponseColumns)
      .from(users)
      .where(eq(users.id, userId));
    return c.json({ user, ...tokens }, 200);
  })

  /** Ends the current device session; its access token stops working immediately. */
  .post('/logout', requireAuth, async (c) => {
    await revokeSession(c.var.db, c.var.user.sessionId);
    return c.body(null, 204);
  })

  .get('/me', requireAuth, async (c) => {
    const db = c.var.db;
    const [user] = await db
      .select(userResponseColumns)
      .from(users)
      .where(eq(users.id, c.var.user.id));
    return c.json(user);
  });
