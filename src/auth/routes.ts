import { and, eq, isNull, ne } from 'drizzle-orm';
import { Hono, type Context } from 'hono';
import { z } from 'zod';

import { isUniqueViolation } from '../db/errors';
import { PLATFORMS, sessions, users } from '../db/schema';
import type { AppEnv } from '../env';
import { AppError } from '../lib/app-error';
import { parseBody } from '../lib/validation';
import { authRateLimit, requireAuth } from './middleware';
import {
  hashPassword,
  needsRehash,
  simulatePasswordCheck,
  verifyPassword,
} from './password';
import { issueReauthToken, verifyReauthToken } from './reauth';
import {
  type ClientMeta,
  createSession,
  revokeSession,
  rotateSession,
} from './sessions';

export const userResponseColumns = {
  id: users.id,
  email: users.email,
  fullName: users.fullName,
  role: users.role,
  isActive: users.isActive,
  createdAt: users.createdAt,
};

/** Optional device info sent by the mobile app; one session is kept per device. */
const deviceFields = {
  /** Stable per-install id generated by the app. */
  deviceId: z.string().max(200).optional(),
  /** Human readable, e.g. "Pixel 8". */
  deviceName: z.string().max(200).optional(),
  platform: z.enum(PLATFORMS).optional(),
};

const email = z.string().trim().toLowerCase().pipe(z.email().max(254));

const loginSchema = z.strictObject({
  email,
  password: z.string().min(1).max(128),
  ...deviceFields,
});

export const PASSWORD_MIN_LENGTH = 8;

/** Self-service sign-up. The role is always USER; hosts and admins are promoted in the database. */
const registerSchema = z.strictObject({
  email,
  password: z.string().min(PASSWORD_MIN_LENGTH).max(128),
  fullName: z.string().trim().min(1).max(100),
  ...deviceFields,
});

const refreshSchema = z.strictObject({
  refreshToken: z.string().min(1).max(512),
});

const profileSchema = z.strictObject({
  fullName: z.string().trim().min(1).max(100),
});

const reauthSchema = z.strictObject({
  password: z.string().min(1).max(128),
});

const reauthTokenField = { reauthToken: z.string().min(1).max(1024) };

const changePasswordSchema = z.strictObject({
  ...reauthTokenField,
  newPassword: z.string().min(PASSWORD_MIN_LENGTH).max(128),
});

const deleteAccountSchema = z.strictObject(reauthTokenField);

const invalidCredentials = () =>
  AppError.unauthorized(
    'INVALID_CREDENTIALS',
    'Email or password is incorrect',
  );

function clientMeta(c: Context): ClientMeta {
  return {
    ip: c.req.header('cf-connecting-ip') ?? undefined,
    userAgent: c.req.header('user-agent')?.slice(0, 500),
  };
}

/**
 * Email + password accounts stored in the User table (passwords hashed with PBKDF2, see password.ts).
 * Anyone can register as USER; admins are created by the seed script.
 */
export const authRoutes = new Hono<AppEnv>()
  .post('/register', authRateLimit, async (c) => {
    const input = await parseBody(c, registerSchema);
    const config = c.var.config;
    const db = c.var.db;
    const passwordHash = await hashPassword(
      input.password,
      config.PASSWORD_HASH_ITERATIONS,
    );
    let user;
    try {
      [user] = await db
        .insert(users)
        .values({
          email: input.email,
          fullName: input.fullName,
          passwordHash,
          role: 'USER',
        })
        .returning(userResponseColumns);
    } catch (error) {
      if (isUniqueViolation(error, 'User.email')) {
        throw AppError.conflict(
          'EMAIL_TAKEN',
          'An account with this email already exists',
        );
      }
      throw error;
    }
    const tokens = await createSession(
      db,
      config,
      user.id,
      input,
      clientMeta(c),
    );
    return c.json({ user, ...tokens }, 201);
  })

  .post('/login', authRateLimit, async (c) => {
    const input = await parseBody(c, loginSchema);
    const config = c.var.config;
    const db = c.var.db;
    const [account] = await db
      .select({ ...userResponseColumns, passwordHash: users.passwordHash })
      .from(users)
      .where(eq(users.email, input.email))
      .limit(1);
    if (!account) {
      // Same work as a real check so timing does not reveal which emails exist.
      await simulatePasswordCheck(
        input.password,
        config.PASSWORD_HASH_ITERATIONS,
      );
      throw invalidCredentials();
    }
    const { passwordHash, ...user } = account;
    if (!(await verifyPassword(input.password, passwordHash))) {
      throw invalidCredentials();
    }
    if (!user.isActive) {
      throw new AppError(
        403,
        'ACCOUNT_DISABLED',
        'This account has been disabled',
      );
    }

    const iterations = config.PASSWORD_HASH_ITERATIONS;
    const rehash = needsRehash(passwordHash, iterations)
      ? db
          .update(users)
          .set({ passwordHash: await hashPassword(input.password, iterations) })
          .where(eq(users.id, user.id))
      : undefined;
    const [tokens] = await Promise.all([
      createSession(db, config, user.id, input, clientMeta(c)),
      rehash,
    ]);
    return c.json({ user, ...tokens }, 200);
  })

  /** Exchanges a refresh token for a new access + refresh token pair (the old refresh token is rotated). */
  .post('/refresh', authRateLimit, async (c) => {
    const { refreshToken } = await parseBody(c, refreshSchema);
    const db = c.var.db;
    const { userId, tokens } = await rotateSession(
      db,
      c.var.config,
      refreshToken,
      clientMeta(c),
    );
    const [user] = await db
      .select(userResponseColumns)
      .from(users)
      .where(eq(users.id, userId));
    return c.json({ user, ...tokens }, 200);
  })

  /** Ends the current device session; its access token stops working immediately. */
  .post('/logout', requireAuth, async (c) => {
    await revokeSession(c.var.db, c.var.user.sessionId);
    return c.body(null, 204);
  })

  .get('/me', requireAuth, async (c) => {
    const db = c.var.db;
    const [user] = await db
      .select(userResponseColumns)
      .from(users)
      .where(eq(users.id, c.var.user.id));
    return c.json(user);
  })

  .patch('/me', requireAuth, async (c) => {
    const { fullName } = await parseBody(c, profileSchema);
    const [user] = await c.var.db
      .update(users)
      .set({ fullName })
      .where(eq(users.id, c.var.user.id))
      .returning(userResponseColumns);
    return c.json(user);
  })

  /**
   * Confirms the password before a sensitive change and returns a short-lived token for it. Split
   * from those changes so that no request hashes twice (10 ms CPU budget, see AGENTS.md).
   */
  .post('/reauth', authRateLimit, requireAuth, async (c) => {
    const { password } = await parseBody(c, reauthSchema);
    const { id, sessionId } = c.var.user;
    const [account] = await c.var.db
      .select({ passwordHash: users.passwordHash })
      .from(users)
      .where(eq(users.id, id));
    if (!account || !(await verifyPassword(password, account.passwordHash))) {
      // Not 401: the client signs out on 401, and the session itself is fine.
      throw AppError.badRequest('WRONG_PASSWORD', 'The password is incorrect');
    }
    return c.json(
      await issueReauthToken(c.var.config, { userId: id, sessionId }),
      200,
    );
  })

  /** Sets a new password and signs out every other device. */
  .post('/change-password', requireAuth, async (c) => {
    const input = await parseBody(c, changePasswordSchema);
    const { id, sessionId } = c.var.user;
    await verifyReauthToken(c.var.config, input.reauthToken, {
      userId: id,
      sessionId,
    });
    const passwordHash = await hashPassword(
      input.newPassword,
      c.var.config.PASSWORD_HASH_ITERATIONS,
    );
    const db = c.var.db;
    await db.batch([
      db.update(users).set({ passwordHash }).where(eq(users.id, id)),
      db
        .update(sessions)
        .set({ revokedAt: new Date() })
        .where(
          and(
            eq(sessions.userId, id),
            ne(sessions.id, sessionId),
            isNull(sessions.revokedAt),
          ),
        ),
    ]);
    return c.body(null, 204);
  })

  /** Ends every session of the user, this device included. */
  .post('/logout-all', requireAuth, async (c) => {
    await c.var.db
      .update(sessions)
      .set({ revokedAt: new Date() })
      .where(
        and(eq(sessions.userId, c.var.user.id), isNull(sessions.revokedAt)),
      );
    return c.body(null, 204);
  })

  /**
   * Deletes a student account with its sessions and attempts (FK cascade). Hosts and admins own
   * shared content (topics, questions, exams), so they cannot delete themselves here.
   */
  .delete('/me', requireAuth, async (c) => {
    const { reauthToken } = await parseBody(c, deleteAccountSchema);
    const { id, sessionId, role } = c.var.user;
    await verifyReauthToken(c.var.config, reauthToken, {
      userId: id,
      sessionId,
    });
    if (role !== 'USER') {
      throw new AppError(
        403,
        'ACCOUNT_NOT_DELETABLE',
        'Authors and admins cannot delete their account from the app',
      );
    }
    await c.var.db.delete(users).where(eq(users.id, id));
    return c.body(null, 204);
  });
